function results = run_section52_all_peppers_200s(resetSession)
%RUN_SECTION52_ALL_100S Convenience entry for all 100-second Section 5.2 tests.
if nargin < 1, resetSession = true; end
if resetSession, restoredefaultpath; end

scriptDir = fileparts(mfilename('fullpath'));
addpath(scriptDir);
if resetSession
    clear functions;
    close all;
    clc;
end

% Changing beta0 also updates the fixed SADMM step denominators below.
beta0 = 50;

% Alg.1 settings are synchronized with Desktop/实验1.  SADMM settings
% below remain fixed throughout each baseline run.
results = run_section52_image_denoising(struct( ...
    'cases', {{'peppers'}}, ...%, , 'bird''boat''peppers''clock','peppers'
    'methods', {{'sadmm_timevarying','svrgadmm','bsarah','svrg','saga','sarah'}}, ...%', ,
    'batchFractions', 0.2, ...
    'usePaperObservation', false, ...
    'noiseDistribution', 'laplace', ...
    'noiseMean', 0, ...
    'lambdaY', 0.05, ...
    'priorDelta', 0.3, ...
    'plot', true, ...
    'plotCurves', true, ...
    'plotNoiseSummary', false, ...
    'plotDecomposition', false, ...
    'plotObjectiveBreakdown', false, ...
    'saveOutputs', true, ...
    'solverOpts', struct( ...
    'mode', 'constrained', ...
    'maxTime', 200, ...
    'numInnerIters', 1, ...
    'beta0Original', beta0, ...
    's', 0.8, ...
    'delta', 0.8, ...
    'varrho', 0.3, ...
    'epsXi', 0.1, ...
    'zeta1', 0.9, ...
    'zeta2', 0.4, ...
    'xi0', 0.1, ...
    'tau', 1e-3, ...
    'Py', 0.05, ...
    'alg1RefreshPeriod', 10, ...
    'K0', 2000, ...
    'gammaMax', 0.5, ...
    'gammaScale', 1.5, ...
    'gammaPower', 2, ...
    'hessianRefreshInterval', 5, ...
    'hessianMinEigOriginal', 1, ...
    'hessianSafety', 1e-10, ...
    'alg1YMaxIter', 25, ...
    'alg1YTol', 1e-4, ...
    'alg1PcgTol', 1e-4, ...
    'alg1PcgMaxIter', 50, ...
    'alg1UseSpectralShift', false, ...
    'sadmmTauSVRG', min(0.05, beta0 / 2), ...
    'sadmmTauSARAH', min(0.05, beta0 / 2), ...
    'sadmmSigma', 0.95, ...
    'sadmmSnapshotPeriod', 10, ...
    'sadmmSarahRefreshPeriod', 10, ...
    'sadmmYMaxIter', 25, ...
    'sadmmYTol', 1e-4, ...
    'timeVaryingEtaScale', 0.002, ...
    'timeVaryingEtaPower', 0.05, ...
    'timeVaryingRho', 0.01, ...
    'timeVaryingBatchFraction', 0.10, ...
    'timeVaryingYMaxIter', 1, ...
    'timeVaryingYTol', 1e-3, ...
    'psnrTarget', inf, ...
    'randomSeed', 20260731, ...
    'verbose', false ...
) ...
));

caseNames = fieldnames(results);
for c = 1:numel(caseNames)
    fprintf('\n[%s]\n', caseNames{c});
    fprintf('noise=%s, usePaperObservation=%d\n', ...
        results.(caseNames{c}).problem.metadata.noiseDistribution, ...
        results.(caseNames{c}).problem.metadata.usePaperObservation);
    methodNames = fieldnames(results.(caseNames{c}).histories);
    for i = 1:numel(methodNames)
        h = results.(caseNames{c}).histories.(methodNames{i});
        methodLabel = results.(caseNames{c}).legendLabels.(methodNames{i});
        fprintf('%s & %.6e & %.6e & %.4f\n', ...
            methodLabel, h.obj(end), h.residual(end), h.psnr(end));
    end
end
end
