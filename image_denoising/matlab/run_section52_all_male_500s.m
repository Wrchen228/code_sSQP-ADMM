function results = run_section52_all_male_500s(resetSession)
%RUN_SECTION52_ALL_MALE_600S Run all six Section 5.2 methods on Male.
% The 1024-by-1024 Male image uses the same noise model and solver setup
% as peppers, with a 600-second cap per method.
if nargin < 1, resetSession = true; end
if resetSession, restoredefaultpath; end

scriptDir = fileparts(mfilename('fullpath'));
addpath(scriptDir);
if resetSession
    clear functions;
    close all;
    clc;
end

beta0 = 50;
results = run_section52_image_denoising(struct( ...
    'cases', {{'male'}}, ...
    'methods', {{'sadmm_timevarying','svrgadmm','bsarah','svrg','saga','sarah'}}, ...
    'batchFractions', 0.11, ...
    'usePaperObservation', false, ...
    'noiseDistribution', 'laplace', ...
    'noiseMean', 0, ...
    'lambdaY', 0.05, ...
    'priorDelta', 0.5, ...
    'plot', true, ...
    'plotCurves', true, ...
    'plotNoiseSummary', false, ...
    'plotDecomposition', false, ...
    'plotObjectiveBreakdown', false, ...
    'saveOutputs', true, ...
    'solverOpts', struct( ...
    'mode', 'constrained', ...
    'maxIter', 500000, ...
    'maxTime', 800, ...
    'numInnerIters', 1, ...
    'beta0Original', beta0, ...
    's', 0.8, ...
    'delta', 0.8, ...
    'varrho', 0.5, ...
    'epsXi', 0.1, ...
    'zeta1', 0.9, ...
    'zeta2', 0.4, ...
    'xi0', 0.1, ...
    'tau', 1e-3, ...
    'Py', 0.05, ...
    'alg1RefreshPeriod', 10, ...
    'K0', 2000, ...
    'gammaMax', 0.5, ...
    'gammaScale', 1.5, ...
    'gammaPower', 2, ...
    'hessianRefreshInterval', 5, ...
    'hessianMinEigOriginal', 1, ...
    'hessianSafety', 1e-10, ...
    'alg1YMaxIter', 25, ...
    'alg1YTol', 1e-4, ...
    'alg1PcgTol', 1e-4, ...
    'alg1PcgMaxIter', 50, ...
    'alg1UseSpectralShift', false, ...
    'sadmmTauSVRG', 0.01, ...
    'sadmmTauSARAH', 0.01, ...
    'sadmmSigma', 0.95, ...
    'sadmmSnapshotPeriod', 10, ...
    'sadmmSarahRefreshPeriod', 10, ...
    'sadmmYMaxIter', 25, ...
    'sadmmYTol', 1e-4, ...
    'timeVaryingEtaScale', 0.002, ...
    'timeVaryingEtaPower', 0.05, ...
    'timeVaryingRho', 0.01, ...
    'timeVaryingBatchFraction', 0.10, ...
    'timeVaryingYMaxIter', 1, ...
    'timeVaryingYTol', 1e-3, ...
    'psnrTarget', inf, ...
    'randomSeed', 20260731, ...
    'verbose', false ...
) ...
));

male = results.male;
fprintf('\n[male: 1024x1024, Laplace stationary noise]\n');
for i = 1:numel(fieldnames(male.histories))
    names = fieldnames(male.histories);
    h = male.histories.(names{i});
    fprintf('%s & %.6e & %.6e & %.4f\n', ...
        male.legendLabels.(names{i}), h.obj(end), h.residual(end), h.psnr(end));
end
end
